def area(a, h):
    '''Принимает основание a и высоту h, возвращает площадь треугольника.
    Пример вызова: area(4, 5) -> 10.0'''
    return a * h / 2


def perimeter(a, b, c):
    '''Принимает стороны треугольника a, b, c, возвращает его периметр.
    Пример вызова: perimeter(3, 4, 5) -> 12'''
    return a + b + c
