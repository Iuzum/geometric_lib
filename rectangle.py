def area(a, b): 
    '''Принимает стороны прямоугольника a и b (int/float), возвращает его площадь.
    Пример вызова: area(3, 4) -> 12'''
    return a * b 

def perimeter(a, b): 
    '''Принимает стороны прямоугольника a и b (int/float), возвращает его площадь.
    Пример вызова: area(3, 4) -> 12'''
    return (a + b) * 2
